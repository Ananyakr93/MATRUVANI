export function calculate_epds_score(answers) {
  if (!answers || answers.length !== 10) {
    return { epds_score: 0, risk_level: 'LOW' }
  }

  let total_score = 0
  
  for (let i = 0; i < 10; i++) {
    const q_num = i + 1
    const q_data = EPDS_QUESTIONS[q_num]
    const ans = answers[i]
    
    // Reverse scoring logic
    if (q_data.scoring === 'reverse') {
      total_score += (3 - ans)
    } else {
      total_score += ans
    }
  }

  let risk_level = 'LOW'
  
  // Q10 override: If score for Q10 is > 0 (meaning anything other than "Never")
  const q10_data = EPDS_QUESTIONS[10]
  const q10_ans = answers[9]
  const q10_score = q10_data.scoring === 'reverse' ? (3 - q10_ans) : q10_ans

  if (q10_score > 0) {
    risk_level = 'HIGH'
  } else if (total_score >= 13) {
    risk_level = 'HIGH'
  } else if (total_score >= 10) {
    risk_level = 'MODERATE'
  }

  return { epds_score: total_score, risk_level }
}
